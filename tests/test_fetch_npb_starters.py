from datetime import datetime
from zoneinfo import ZoneInfo

from scripts.fetch_npb_starters import parse_starters_html


def test_parse_starters_uses_nearest_team_image_alt():
    html = b"""
    <html><body><h3>9\xe6\x9c\x8813\xe6\x97\xa5\xe3\x81\xae\xe4\xba\x88\xe5\x91\x8a\xe5\x85\x88\xe7\x99\xba\xe6\x8a\x95\xe6\x89\x8b</h3>
      <div class="game">
        <div><img alt="\xe7\xa6\x8f\xe5\xb2\xa1\xe3\x82\xbd\xe3\x83\x95\xe3\x83\x88\xe3\x83\x90\xe3\x83\xb3\xe3\x82\xaf\xe3\x83\x9b\xe3\x83\xbc\xe3\x82\xaf\xe3\x82\xb9"><a href="/bis/players/1.html">\xe4\xb8\x8a\xe8\x8c\xb6\xe8\xb0\xb7\xe3\x80\x80\xe5\xa4\xa7\xe6\xb2\xb3</a></div>
        <div><img alt="\xe5\x8d\x83\xe8\x91\x89\xe3\x83\xad\xe3\x83\x83\xe3\x83\x86\xe3\x83\x9e\xe3\x83\xaa\xe3\x83\xbc\xe3\x83\xb3\xe3\x82\xba"><a href="/bis/players/2.html">J.\xe3\x83\xab\xe3\x82\xb1\xe3\x83\xbc\xe3\x82\xb7\xe3\x83\xbc</a></div>
      </div>
    </body></html>
    """
    payload = parse_starters_html(
        html,
        datetime(2026, 9, 13, 6, 0, tzinfo=ZoneInfo("Asia/Tokyo")),
    )

    assert payload["date"] == "2026-09-13"
    assert payload["starters"] == {
        "ソフトバンク": "上茶谷　大河",
        "ロッテ": "J.ルケーシー",
    }
